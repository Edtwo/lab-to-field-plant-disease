"""Aggregate results/runs/* into results/summary.md, results/tables/*.tex and results/figures/*.pdf.
Nothing here is typed by hand: every number is read from metrics.json / logits files.
Usage: python scripts/summarize.py
"""
import glob, json, os, re, sys
import numpy as np

sys.stdout.reconfigure(encoding="utf-8")

CACHE = os.environ.get("HV_CACHE", "data/cache")
MODELS = ["mnv3", "effb0", "dinov2s_lp", "dinov2s_ft"]
NICE = {"mnv3": "MobileNetV3-L", "effb0": "EfficientNet-B0", "dinov2s_lp": "DINOv2 ViT-S/14 (linear probe)",
        "dinov2s_ft": "DINOv2 ViT-S/14 (fine-tune)", "clip": "CLIP ViT-B/32 (zero-shot)"}
REGIMES = [("pv_pre", "PV only (0 field)"), ("pd_k5_init", "PV $\\rightarrow$ 5/class field"),
           ("pd_all_init", "PV $\\rightarrow$ all field"), ("pd_k5_pre", "5/class field only"),
           ("pd_all_pre", "all field only")]
SEEDS = [0, 1, 2]
os.makedirs("results/tables", exist_ok=True); os.makedirs("results/figures", exist_ok=True)


def load(name):
    p = f"results/runs/{name}/metrics.json"
    return json.load(open(p)) if os.path.exists(p) else None


def get(m, reg, split="pd_test", key="top1"):
    v = [load(f"{m}_{reg}_s{s}") for s in SEEDS]
    v = [r[split][key] for r in v if r and split in r]
    return np.array(v)


def ms(a, d=1):
    if len(a) == 0:
        return "\\TODO{result}"
    return f"{a.mean():.{d}f} $\\pm$ {a.std(ddof=1) if len(a) > 1 else 0:.{d}f}" + ("" if len(a) == 3 else f" (n={len(a)})")


def md(s):
    return s.replace("$\\pm$", "±").replace("$\\rightarrow$", "→")


def boot_ci(name, split="pd_test", B=2000):
    """95% bootstrap CI of top-1 over test images, for one run (resampling test images)."""
    p = f"results/runs/{name}/logits_{split}.npy"
    if not os.path.exists(p):
        return None
    pred = np.load(p).argmax(1); y = np.load(os.path.join(CACHE, f"{split}_y.npy"))
    c = (pred == y).astype(float); rng = np.random.RandomState(0)
    bs = [c[rng.randint(0, len(c), len(c))].mean() * 100 for _ in range(B)]
    return np.percentile(bs, [2.5, 97.5])


def paired_diff(a_runs, b_runs, split="pd_test", B=5000):
    """Mean over seeds of top-1(a) - top-1(b), with a paired bootstrap 95% CI.
    Each bootstrap draw resamples PlantDoc test images once and applies the same indices to every run,
    so test-set sampling noise is shared between the two arms."""
    y = np.load(os.path.join(CACHE, f"{split}_y.npy"))
    ca = [(np.load(f"results/runs/{r}/logits_{split}.npy").argmax(1) == y).astype(float) for r in a_runs]
    cb = [(np.load(f"results/runs/{r}/logits_{split}.npy").argmax(1) == y).astype(float) for r in b_runs]
    A, Bm = np.mean(ca, 0), np.mean(cb, 0)  # per-image seed-averaged correctness
    rng = np.random.RandomState(0); n = len(y)
    d = [(A[i] - Bm[i]).mean() * 100 for i in (rng.randint(0, n, n) for _ in range(B))]
    lo, hi = np.percentile(d, [2.5, 97.5])
    return (A - Bm).mean() * 100, lo, hi


def main():
    out = ["# Results summary (auto-generated by `scripts/summarize.py`; do not edit by hand)\n"]
    runs = sorted(glob.glob("results/runs/*/metrics.json"))
    secs = sum(json.load(open(r)).get("total_seconds", 0) for r in runs)
    out.append(f"Runs found: {len(runs)}. Sum of per-run wall-clock: {secs/3600:.2f} GPU-hours (training + evaluation).\n")
    clip = load("clip_b32_zeroshot")

    # ---- Table 1: source-only
    rows = []
    for m in MODELS:
        pv, pd, pdd, f1 = get(m, "pv_pre", "pv_test"), get(m, "pv_pre"), get(m, "pv_pre", "pd_test_dedup"), get(m, "pv_pre", "pd_test", "macro_f1")
        gap = pv - pd if len(pv) == len(pd) else np.array([])
        ci = [boot_ci(f"{m}_pv_pre_s{s}") for s in SEEDS]; ci = [c for c in ci if c is not None]
        hw = f"{np.mean([(c[1]-c[0])/2 for c in ci]):.1f}" if ci else "\\TODO{result}"
        rows.append((NICE[m], ms(pv), ms(pd), ms(pdd), ms(f1), ms(gap), hw))
    if clip:
        rows.append((NICE["clip"], f"{clip['pv_test']['top1']:.1f}", f"{clip['pd_test']['top1']:.1f}",
                     f"{clip['pd_test_dedup']['top1']:.1f}", f"{clip['pd_test']['macro_f1']:.1f}",
                     f"{clip['pv_test']['top1']-clip['pd_test']['top1']:.1f}", "--"))
    hdr = ["Model", "PV test top-1", "PlantDoc top-1", "PlantDoc dedup top-1", "PlantDoc macro-F1", "Gap (PV−PD)", "±95% CI half-width (bootstrap)"]
    out.append("## Table 1: Trained on PlantVillage only (28 classes), mean ± std over 3 seeds\n")
    out.append("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    out += ["| " + " | ".join(md(c) for c in r) + " |" for r in rows]
    with open("results/tables/source_only.tex", "w") as f:
        f.write("\\begin{tabular}{lcccccc}\\toprule\n")
        f.write("Model & PV & PD & PD$_\\text{dedup}$ & PD F1 & Gap & CI$_{95}$ \\\\\\midrule\n")
        for r in rows:
            f.write(" & ".join(r) + " \\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")

    # ---- Table 2: field labels
    out.append("\n## Table 2: PlantDoc test top-1 vs. amount of field labels, mean ± std over 3 seeds\n")
    hdr = ["Model"] + [md(n) for _, n in REGIMES]
    out.append("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    T2 = {}
    with open("results/tables/field_labels.tex", "w") as f:
        f.write("\\begin{tabular}{l" + "c" * len(REGIMES) + "}\\toprule\n")
        f.write("Model & " + " & ".join(n for _, n in REGIMES) + " \\\\\\midrule\n")
        for m in MODELS:
            vals = [get(m, r) for r, _ in REGIMES]; T2[m] = vals
            out.append("| " + NICE[m] + " | " + " | ".join(md(ms(v)) for v in vals) + " |")
            f.write(NICE[m] + " & " + " & ".join(ms(v) for v in vals) + " \\\\\n")
        f.write("\\bottomrule\\end{tabular}\n")
    out.append("\nSame table on the de-duplicated PlantDoc test set (near-duplicates of PlantDoc-train removed):\n")
    out.append("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr))
    for m in MODELS:
        out.append("| " + NICE[m] + " | " + " | ".join(md(ms(get(m, r, "pd_test_dedup"))) for r, _ in REGIMES) + " |")

    # ---- Edge
    ep = "results/edge/edge_profile.json"
    E = json.load(open(ep)) if os.path.exists(ep) else None
    out.append("\n## Table 3: Edge cost (batch 1, 224 px)\n")
    if E:
        out.append(f"CPU: {E['cpu']}; GPU: {E['gpu']}; onnxruntime {E['onnxruntime']}; {E['protocol']}\n")
        out.append("| Model | Params (M) | ONNX (MB) | CPU ms (1 thr) | CPU ms (4 thr) | GPU ms (bf16) | GPU peak MB |\n|---|---|---|---|---|---|---|")
        with open("results/tables/edge.tex", "w") as f:
            f.write("\\begin{tabular}{lcccccc}\\toprule\nModel & Params (M) & ONNX (MB) & CPU-1 (ms) & CPU-4 (ms) & GPU (ms) & GPU mem (MB) \\\\\\midrule\n")
            for k in ["mnv3", "effb0", "dinov2s_ft"]:
                r = E[k]; nm = NICE[k].replace(" (fine-tune)", "")
                cells = [f"{r['params_M']:.1f}", f"{r['onnx_MB']:.1f}", f"{r['cpu_ms_1thr']:.1f}", f"{r['cpu_ms_4thr']:.1f}", f"{r['gpu_ms']:.2f}", f"{r['gpu_peak_mem_MB']:.0f}"]
                out.append(f"| {nm} | " + " | ".join(cells) + " |")
                f.write(nm + " & " + " & ".join(cells) + " \\\\\n")
            f.write("\\bottomrule\\end{tabular}\n")
    else:
        out.append("\\TODO{result}: edge profile not run yet.")

    # ---- Claims
    out.append("\n## Claim check (thresholds fixed in notes/plan.md before any results)\n")
    def verdict(b): return "HOLDS" if b else "DOES NOT HOLD"
    pv_pd = {m: (get(m, "pv_pre", "pv_test"), get(m, "pv_pre")) for m in MODELS}
    if all(len(a) == 3 and len(b) == 3 for a, b in pv_pd.values()):
        gaps = {m: (a - b).mean() for m, (a, b) in pv_pd.items()}
        out.append(f"- **C1** (every source-only model loses ≥30 pts): mean gaps " + ", ".join(f"{NICE[m]} {g:.1f}" for m, g in gaps.items()) + f" → **{verdict(min(gaps.values()) >= 30)}**")
        d = pv_pd["dinov2s_lp"][1]; best = max(["mnv3", "effb0"], key=lambda m: pv_pd[m][1].mean()); c = pv_pd[best][1]
        thr = np.sqrt(d.std(ddof=1) ** 2 + c.std(ddof=1) ** 2)
        out.append(f"- **C2** (DINOv2-LP > best CNN by > combined std): DINOv2-LP {d.mean():.1f}, {NICE[best]} {c.mean():.1f}, combined std {thr:.1f} → **{verdict(d.mean() - c.mean() > thr)}**")
        sds = {m: pv_pd[m][1].std(ddof=1) for m in MODELS}
        out.append(f"- **C5** (seed std on PlantDoc ≥2 pts for at least one model): " + ", ".join(f"{NICE[m]} {s:.1f}" for m, s in sds.items()) + f" → **{verdict(max(sds.values()) >= 2)}**")
    else:
        out.append("- C1/C2/C5: \\TODO{result} (block A incomplete)")
    if all(all(len(v) == 3 for v in T2.get(m, [[]])[:3]) for m in MODELS):
        rec = {m: (T2[m][1].mean() - T2[m][0].mean()) / max(1e-9, T2[m][2].mean() - T2[m][0].mean()) for m in MODELS}
